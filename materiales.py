# ==================== RESOLUCIÓN DE IDs ====================
# Mapa: id (ej: "material_36") -> nombre real (ej: "Templado Gema Frágil")
_ID_A_NOMBRE: dict = {}
for _k, _v in MATERIALES.items():
    _mid = _v.get("id", _k)
    _nom = _v.get("nombre", "")
    if _mid not in _ID_A_NOMBRE and _nom:
        _ID_A_NOMBRE[_mid] = _nom

def resolver_nombre(id_o_nombre: str) -> str:
    """Convierte un ID de material (ej: 'material_36') en su nombre real.
    Si ya es un nombre real (no coincide con el patrón), lo devuelve tal cual."""
    import re
    if re.match(r'^material_\d+(_normal|_dificil|_raro|_epico)?$', id_o_nombre):
        return _ID_A_NOMBRE.get(id_o_nombre, id_o_nombre)
    return id_o_nombre

def obtener_datos(id_o_nombre: str) -> dict:
    """Devuelve el dict completo del material dado su ID o nombre."""
    # Buscar por ID directo (ej: "material_2")
    for v in MATERIALES.values():
        if v.get("id") == id_o_nombre or v.get("nombre") == id_o_nombre:
            return v
    # Buscar por clave directa (ej: "material_2_normal")
    return MATERIALES.get(id_o_nombre, {})
